"""Generate the small-stack C5 adaptation of the pinned public-domain TinyJPEG."""
from pathlib import Path
import re,json,hashlib
P=Path(__file__).resolve().parent
s=(P/'tiny_jpeg.original.h').read_text()
# Generate the canonical fixed Huffman lookup tables in Flash, not on the stack.
def array(name):
    part=re.search(r'\b'+name+r'\s*\[.*?\]\s*=\s*\{(.*?)\};',s,re.S)[1]
    part=re.sub(r'//[^\n]*','',part)
    return [int(x.strip(),0) for x in part.split(',') if x.strip()]
sizes=[];codes=[]
for name in ['luma_dc','luma_ac','chroma_dc','chroma_ac']:
    lengths=array('tjei_default_ht_'+name+'_len');values=array('tjei_default_ht_'+name)
    sz=[0]*257;co=[0]*256;at=code=0
    for bits,n in enumerate(lengths,1):
        for _ in range(n):sz[values[at]]=bits;co[values[at]]=code;code+=1;at+=1
        code<<=1
    assert at==len(values);sizes.append(sz);codes.append(co)
tables='\n'.join('static const '+typ+' '+name+f'[4][{len(data[0])}]={{'+','.join('{'+','.join(map(str,row))+'}' for row in data)+'};' for typ,name,data in [('uint8_t','c5_huffsize',sizes),('uint16_t','c5_huffcode',codes)])
core=s[s.index('typedef struct\n{\n    void*'):s.index('\nint tje_encode_to_file(',s.index('static int tjei_encode_main'))]
core=core.replace('uint8_t         ehuffsize[4][257];','').replace('uint16_t        ehuffcode[4][256];','')
a=core.index('static uint8_t* tjei_huff_get_code_lengths');b=core.index('\n}',core.index('static void tjei_huff_get_extended'))+2
core=core[:a]+core[b:]
a=core.index('    // How many codes in total');b=core.index('\n}\n',a)
core=core[:a]+core[b:]
core=core.replace('state->ehuffsize','c5_huffsize').replace('state->ehuffcode','c5_huffcode')
a=core.index('                    uint8_t r = src_data');b=core.index('\n                    float luma',a)
core=core[:a]+'''                    uint16_t rgb=c5_frame_pixel((unsigned)(src_index/3)%320u,(unsigned)(src_index/3)/320u);
                    uint8_t r=(uint8_t)(((rgb>>11)&31)*255/31), g=(uint8_t)(((rgb>>5)&63)*255/63), b=(uint8_t)((rgb&31)*255/31);
'''+core[b:]
core=core.replace('for ( int y = 0; y < height; y += 8 ) {','for ( int y = 0; y < height; y += 8 ) {\n        c5_jpeg_yield(); if(((C5JpegOutput*)state->write_context.context)->overflow)return 0;')
# Header-only code uses round-to-nearest away from zero; hardware casts suffice.
core=core.replace('floorf(fval + 0.5f)','(float)(int)(fval + 0.5f)').replace('ceilf(fval - 0.5f)','(float)(int)(fval - 0.5f)')
core=core.replace('floorf(fval + 1024 + 0.5f)','(float)(int)(fval + 1024 + 0.5f)')
prefix=s[:s.index('// ============================================================')]+'''
/* C5 adaptation: fixed Huffman tables in Flash; RGB565 accessor; 64-byte output
 * staging; bounded sink, no files, allocator or full RGB source buffer.
 * Generated by adapt_jpeg.py. Upstream blob e6e68afec3a287ba7f512e44224d3b43d36d36b8. */
#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include "display.h"
#define assert(x) ((void)0)
#define TJE_USE_FAST_DCT 1
#define TJEI_FORCE_INLINE static
#define TJEI_BUFFER_SIZE 64
#define tje_log(x) ((void)0)
#define tjei_min(a,b) ((a)<(b)?(a):(b))
#define tjei_max(a,b) ((a)>(b)?(a):(b))
typedef void tje_write_func(void*,void*,int);
typedef struct {uint8_t *dst; unsigned capacity,used,overflow;} C5JpegOutput;
extern void c5_jpeg_yield(void);
'''
suffix='''
static void c5_jpeg_write(void *ctx,void *data,int n){
    C5JpegOutput *o=ctx;if(n<0 || (unsigned)n>o->capacity-o->used){o->overflow=1;return;}
    if(o->overflow)return;memcpy(o->dst+o->used,data,(unsigned)n);o->used+=(unsigned)n;
}
unsigned c5_jpeg_encode(uint8_t *dst,unsigned capacity,unsigned scale){
    TJEState state={0};C5JpegOutput out={dst,capacity,0,0};
    for(unsigned i=0;i<64;i++){
        unsigned a=tjei_default_qt_luma_from_spec[i]*scale,b=tjei_default_qt_chroma_from_paper[i]*scale;
        state.qt_luma[i]=(uint8_t)(a>255?255:a);state.qt_chroma[i]=(uint8_t)(b>255?255:b);
    }
    state.write_context.context=&out;state.write_context.func=c5_jpeg_write;
    tjei_huff_expand(&state);
    return tjei_encode_main(&state,0,320,172,3) && !out.overflow ? out.used:0;
}
'''
(P/'jpeg.c').write_text(prefix+tables+'\n'+core+suffix)
(P/'jpeg-source.json').write_text(json.dumps(dict(url='https://github.com/serge-rgb/TinyJPEG/blob/master/tiny_jpeg.h',git_blob='e6e68afec3a287ba7f512e44224d3b43d36d36b8',sha256=hashlib.sha256((P/'tiny_jpeg.original.h').read_bytes()).hexdigest(),license='Public domain with irrevocable fallback license'),indent=2)+'\n')
